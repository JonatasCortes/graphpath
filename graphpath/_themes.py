def get_theme(theme_name: str) -> dict[str, str]:
    theme_key: str = theme_name.lower().strip().replace(
        " ", "").replace("-", "").replace("_", "")

    if theme_key in THEMES:
        return THEMES[theme_key]

    raise ValueError(f"Theme '{theme_name}' not found.")
